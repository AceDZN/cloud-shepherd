// Converts the NOAA ETOPO1 (etopo180, 1 arc-minute) CSV extract into a compact
// Int16 base64 module used by both the rule model and the renderer.
import { readFileSync, writeFileSync } from 'node:fs';

const rows = readFileSync(new URL('../data/etopo_israel.csv', import.meta.url), 'utf8').trim().split('\n').slice(2);
const lats = new Set(), lons = new Set();
const pts = rows.map((r) => { const [la, lo, h] = r.split(',').map(Number); lats.add(la); lons.add(lo); return [la, lo, h]; });
const latArr = [...lats].sort((a, b) => a - b), lonArr = [...lons].sort((a, b) => a - b);
const W = lonArr.length, H = latArr.length;
const buf = new Int16Array(W * H);
const li = new Map(latArr.map((v, i) => [v, i])), lo = new Map(lonArr.map((v, i) => [v, i]));
for (const [la, lon, h] of pts) buf[li.get(la) * W + lo.get(lon)] = Math.round(h);
const b64 = Buffer.from(buf.buffer).toString('base64');
const out = `// Generated by scripts/build-dem.mjs from NOAA ETOPO1 (ERDDAP dataset etopo180).
// Row-major, south→north rows, west→east columns, metres (negative = sea floor).
export const DEM_W = ${W};
export const DEM_H = ${H};
export const DEM_LAT0 = ${latArr[0].toFixed(4)};
export const DEM_LON0 = ${lonArr[0].toFixed(4)};
export const DEM_STEP_DEG = ${(1 / 60).toFixed(8)};
export const DEM_B64 = '${b64}';
`;
writeFileSync(new URL('../src/rules/demData.ts', import.meta.url), out);
console.log(W, H, b64.length, Math.min(...buf), Math.max(...buf));
