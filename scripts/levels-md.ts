// Writes LEVELS.md from src/rules/levels.ts and the scripted pilots (so the table never drifts from the game).
import { writeFileSync } from 'node:fs';
import { LEVELS } from '../src/rules/levels.ts';
import { alwaysEast, play, pourAlways, routePilot } from '../src/rules/autopilot.ts';
import { stars } from '../src/rules/sim.ts';

const WORLDS = ['', 'הים והחוף', 'מעל ההרים', 'מפת הגשם של ישראל', 'החורף הארוך'];
let md = `# Levels — Cloud Shepherd\n\nGenerated by \`npx tsx scripts/levels-md.ts\` from \`src/rules/levels.ts\`. "Solution" is the scripted route the tests fly; "naive" pilots pour all the time or steer east all the time.\n\n`;
let world = 0;
for (const l of LEVELS) {
  if (l.world !== world) { world = l.world; md += `\n## World ${world} · ${WORLDS[world]}\n\n| # | Title | Goal | Targets | Player decision | Solution | Naive pilots |\n|---|---|---|---|---|---|---|\n`; }
  const sol = play(l, l.solution.plan, routePilot(l.solution));
  const pa = play(l, l.solution.plan, pourAlways), ae = play(l, l.solution.plan, alwaysEast);
  const tg = l.targets.map((t) => `${t.he}${t.optional ? ' (trap/bonus)' : ''}: ${t.max !== undefined ? `${t.need}–${t.max}` : t.need} ${t.kind === 'shade' ? 's' : 'mm'}${t.kind === 'snow' ? ' snow' : ''}`).join('<br>');
  const dec: string[] = [];
  if (l.plan.slots?.length) dec.push(`place ${l.plan.tokens?.L ? `${l.plan.tokens.L}×ל` : ''}${l.plan.tokens?.H ? ` ${l.plan.tokens.H}×ג` : ''} on ${l.plan.slots.map((s) => s.id).join('/')}`);
  if (l.plan.hours?.length) dec.push(`hour ${l.plan.hours.join('/')}`);
  if (l.storms[0].turnsInto) dec.push('season dial in flight');
  if (l.storms.length > 1) dec.push(`${l.storms.length} storms`);
  dec.push('steer + when to pour');
  const solTxt = `${sol.status} ★${stars(sol)}${l.solution.plan.tokens.length ? ` · ${l.solution.plan.tokens.map((t) => t.slot).join(',')}` : ''}${l.solution.plan.hour !== undefined ? ` @${l.solution.plan.hour}:00` : ''}`;
  const naive = `pour: ${pa.status}${pa.failReason ? ` (${pa.failReason})` : ''} · east: ${ae.status}${ae.failReason ? ` (${ae.failReason})` : ''}`;
  md += `| ${l.id} | ${l.title} | ${l.goal} | ${tg} | ${dec.join('; ')} | ${solTxt} | ${naive} |\n`;
}
md += `\nLevels 11–18 scale rainfall: one storm stands for a month or a whole winter (\`mmScale\`), and the HUD says so. Bands (min–max) fail if overshot.\n`;
writeFileSync('LEVELS.md', md);
console.log('wrote LEVELS.md');
